export function resolveQuoteTemplate(
  templateId?: string, 
  customStyle?: Partial<QuoteTemplateStyle> | QuoteTemplateStyle, 
  customTemplates: QuoteTemplateStyle[] = []
): QuoteTemplateStyle {
  const allTemplates = [...STANDARD_QUOTE_TEMPLATES, ...(Array.isArray(customTemplates) ? customTemplates : [])];
  const base = (templateId ? allTemplates.find(t => t.id === templateId) : undefined) || STANDARD_QUOTE_TEMPLATES[0];

  if (customStyle && typeof customStyle === 'object' && Object.keys(customStyle).length > 0) {
    return { ...base, ...customStyle };
  }
  return base;
}
